
let num = 10;
console.log(`The data type of num variable is : ${typeof(num)}`);

// NUMBER-STRING
let num1 = num - "5";
console.log(`The data type of num1 variable is : ${typeof(num1)}`);

//NUMBER/STRING
let num2 = num/"2";
console.log(`The data type of num2 variable is : ${typeof(num2)}`);

//NUMBER*BOOLEAN
let num3 = num*true;
let num4 = num*false;
console.log(`The data type of num3 variable is : ${typeof(num3)}`);
console.log(`The data type of num4 variable is : ${typeof(num4)}`);

//NUMBER*NULL
let num5 = num*null;
console.log(`The data type of num5 variable is : ${typeof(num5)}`);