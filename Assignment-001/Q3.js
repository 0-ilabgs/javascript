function getDayName(day){

    switch(day){

        case 1:
            console.log("Sunday");
        break;

        case 2:
            console.log("Monday");
        break;

        case 3:
            console.log("Tuesday");
        break;

        case 4:
            console.log("Wednesday");
        break;

        case 5:
            console.log("Thersday");
        break;

        case 6:
            console.log("Friday");
        break;

        case 7:
            console.log("Satarday");
        break;
        
    }
}

const Num = 1;
getDayName(Num);
